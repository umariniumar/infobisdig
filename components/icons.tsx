export type IconName = keyof typeof PATHS;

export function Icon({
  name,
  size = 20,
  className,
}: {
  name: IconName;
  size?: number;
  className?: string;
}) {
  return (
    <svg
      aria-hidden="true"
      className={className}
      fill="none"
      height={size}
      stroke="currentColor"
      strokeLinecap="round"
      strokeLinejoin="round"
      strokeWidth={2}
      viewBox="0 0 24 24"
      width={size}
    >
      {PATHS[name]}
    </svg>
  );
}

// Ikon per mata kuliah (dipakai di kartu dan bottom sheet).
export function subjectIcon(subject: string): IconName {
  const s = subject.toLowerCase();
  if (s.includes("crm") || s.includes("customer")) return "users";
  if (s.includes("ekonomi")) return "globe";
  if (s.includes("hukum")) return "shield";
  if (s.includes("risiko")) return "shield";
  if (s.includes("web")) return "code";
  if (s.includes("analytics") || s.includes("big data")) return "chart";
  if (s.includes("database")) return "database";
  if (s.includes("keuangan") || s.includes("fintech")) return "trend";
  return "book";
}
