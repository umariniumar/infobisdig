-- Skema Supabase untuk Dashboard Informasi Terkurasi
-- Cara pakai: buka Supabase Dashboard → SQL Editor → tempel seluruh isi file ini → Run.
-- Setelah itu jalankan: npm run seed:supabase  (butuh SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY di .env.local)
--
-- Keamanan: aktifkan Row Level Security (RLS) dan biarkan tabel hanya bisa
-- dibaca publik (select). Tulis HANYA lewat service role key dari server
-- Next.js (API route kurator). JANGAN pernah menaruh service role key di kode
-- yang bisa dilihat browser.

create table if not exists schedule_items (
  id bigint generated by default as identity primary key,
  subject text not null,
  date date not null,
  start_time text not null,
  end_time text not null,
  lecturer text not null default '',
  location text not null default '',
  mode text not null default 'kelas' check (mode in ('kelas','zoom','pengganti','lainnya')),
  origin text not null default 'sevima' check (origin in ('sevima','tambahan')),
  note text not null default '',
  is_example boolean not null default false
);

create table if not exists info_posts (
  id bigint generated by default as identity primary key,
  title text not null,
  body text not null default '',
  category text not null default 'pengumuman' check (category in ('pengumuman','jadwal','tugas','kegiatan')),
  subject text not null default '',
  source text not null default '',
  pinned boolean not null default false,
  urgent boolean not null default false,
  expires_date date,
  media_type text not null default '' check (media_type in ('','image','video')),
  media_url text not null default '',
  media_blob_key text not null default '',
  media_from_upload boolean not null default false,
  created_at timestamptz not null default now(),
  is_example boolean not null default false
);

create table if not exists tasks (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null default '',
  subject text not null default '',
  deadline_date date not null,
  deadline_time text not null default '23:59',
  is_example boolean not null default false
);

create table if not exists articles (
  id bigint generated by default as identity primary key,
  title text not null,
  summary text not null default '',
  body text not null default '',
  subject text not null default '',
  source text not null default '',
  url text not null default '',
  reading_minutes int not null default 5,
  media_type text not null default '' check (media_type in ('','image','video')),
  media_url text not null default '',
  media_blob_key text not null default '',
  media_from_upload boolean not null default false,
  created_at timestamptz not null default now(),
  is_example boolean not null default false
);

-- RLS: baca bebas, tulis hanya service role (melewati RLS).
alter table schedule_items enable row level security;
alter table info_posts enable row level security;
alter table tasks enable row level security;
alter table articles enable row level security;

drop policy if exists "baca bebas" on schedule_items;
create policy "baca bebas" on schedule_items for select using (true);
drop policy if exists "baca bebas" on info_posts;
create policy "baca bebas" on info_posts for select using (true);
drop policy if exists "baca bebas" on tasks;
create policy "baca bebas" on tasks for select using (true);
drop policy if exists "baca bebas" on articles;
create policy "baca bebas" on articles for select using (true);

-- Penjaga urutan id (identity sequence) setelah seed.
-- Seed memasukkan baris dengan id eksplisit (jadwal 1–67, info 1–3, tugas 1–4,
-- artikel 1–10), sementara sequence identity tiap tabel masih di 1 — tanpa
-- reset, insert kurator berikutnya gagal "duplicate key value violates unique
-- constraint ..._pkey". Script seed memanggil fungsi ini setelah upsert.
-- Bila setup dari nol, jalankan file ini (atau potongan fungsi ini) di SQL Editor.
create or replace function public.reset_identity_sequences()
returns void
language sql
security definer
as $$
  select setval(pg_get_serial_sequence('schedule_items', 'id'), (select max(id) from schedule_items));
  select setval(pg_get_serial_sequence('info_posts', 'id'), (select max(id) from info_posts));
  select setval(pg_get_serial_sequence('tasks', 'id'), (select max(id) from tasks));
  select setval(pg_get_serial_sequence('articles', 'id'), (select max(id) from articles));
$$;

revoke all on function public.reset_identity_sequences() from public;
grant execute on function public.reset_identity_sequences() to service_role;
